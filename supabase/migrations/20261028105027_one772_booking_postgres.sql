-- ONE-772: fresh private booking database; no historical booking import.
-- Credentials are provisioned separately, never stored in migration history.
CREATE ROLE oneplace_booking LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
ALTER ROLE oneplace_booking SET search_path = booking, pg_catalog;
CREATE SCHEMA booking;
REVOKE ALL ON SCHEMA booking FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA booking TO oneplace_booking;

CREATE TABLE booking.booking_templates (
  bt_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "bt_projectId" varchar(128) NOT NULL UNIQUE,
  bt_name varchar(255) NOT NULL,
  "bt_templateType" varchar(64) NOT NULL,
  "bt_liffId" varchar(255),
  "bt_ragicSearchPath" varchar(255) NOT NULL,
  "bt_ragicUidField" varchar(128) NOT NULL,
  "bt_ragicTaskPath" varchar(255) NOT NULL,
  "bt_slotDurationMinutes" integer NOT NULL DEFAULT 60,
  "bt_bookableDaysAhead" integer NOT NULL DEFAULT 14,
  "bt_dailyStartTime" varchar(5) NOT NULL DEFAULT '09:00',
  "bt_dailyEndTime" varchar(5) NOT NULL DEFAULT '18:00',
  "bt_bufferMinutes" integer NOT NULL DEFAULT 0,
  "bt_bufferDirection" varchar(16) NOT NULL DEFAULT 'after',
  "bt_weeklyHours" jsonb,
  "bt_instructionEnabled" boolean NOT NULL DEFAULT false,
  "bt_instructionText" text,
  "bt_minLeadDays" integer NOT NULL DEFAULT 0,
  "bt_contractAction" varchar(32),
  "bt_isActive" boolean NOT NULL DEFAULT true,
  "bt_createdByUserId" integer,
  "bt_createdAt" timestamptz NOT NULL DEFAULT now(),
  "bt_updatedAt" timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE booking.calendar_routing_rules (
  crr_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "crr_templateId" integer NOT NULL REFERENCES booking.booking_templates(bt_id),
  crr_days jsonb NOT NULL,
  "crr_calendarId" varchar(512) NOT NULL,
  "crr_calendarLabel" varchar(256),
  "crr_ownerName" varchar(128) NOT NULL,
  "crr_weeklyStartTime" varchar(5),
  "crr_weeklyEndTime" varchar(5),
  "crr_sortOrder" integer NOT NULL DEFAULT 0,
  "crr_createdAt" timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE booking.booking_form_fields (
  bff_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "bff_templateId" integer NOT NULL REFERENCES booking.booking_templates(bt_id),
  "bff_fieldType" varchar(32) NOT NULL CHECK ("bff_fieldType" IN ('text','select','file','description','checkbox','line_uid','inbox_url')),
  bff_label varchar(255) NOT NULL DEFAULT '',
  "bff_isRequired" boolean NOT NULL DEFAULT false,
  bff_options jsonb,
  "bff_ragicFieldId" varchar(64),
  "bff_descriptionText" text,
  "bff_allowOther" boolean NOT NULL DEFAULT false,
  "bff_selectionMode" varchar(16) DEFAULT 'checkbox' CHECK ("bff_selectionMode" IN ('radio','checkbox')),
  "bff_sortOrder" integer NOT NULL DEFAULT 0,
  "bff_createdAt" timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE booking.booking_records (
  br_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "br_templateId" integer NOT NULL REFERENCES booking.booking_templates(bt_id),
  "br_tenantUid" varchar(255) NOT NULL,
  "br_tenantUserId" integer,
  "br_tenantName" varchar(128),
  "br_roomNumber" varchar(64),
  br_address varchar(512),
  "br_bookingTime" bigint NOT NULL,
  "br_durationMinutes" integer NOT NULL,
  "br_assigneeName" varchar(128),
  "br_googleEventId" varchar(512),
  "br_googleCalendarId" varchar(512),
  "br_ragicRecordId" varchar(64),
  "br_formAnswers" jsonb,
  br_status varchar(16) NOT NULL DEFAULT 'confirmed' CHECK (br_status IN ('confirmed','cancelled','completed','no_show')),
  "br_cancelReason" text,
  "br_createdAt" timestamptz NOT NULL DEFAULT now(),
  "br_updatedAt" timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE booking.booking_submission_attempts (
  request_key varchar(64) PRIMARY KEY,
  payload_hash varchar(64) NOT NULL,
  state varchar(32) NOT NULL CHECK (state IN ('processing','ragic_written','completed','needs_review')),
  ragic_record_id varchar(64),
  booking_id integer REFERENCES booking.booking_records(br_id),
  failure_stage varchar(32),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX "crr_templateId_idx" ON booking.calendar_routing_rules ("crr_templateId");
CREATE INDEX "bff_templateId_idx" ON booking.booking_form_fields ("bff_templateId");
CREATE INDEX "br_templateId_idx" ON booking.booking_records ("br_templateId");
CREATE INDEX "br_tenantUid_idx" ON booking.booking_records ("br_tenantUid");
CREATE INDEX "br_tenantUserId_idx" ON booking.booking_records ("br_tenantUserId");
CREATE INDEX "br_bookingTime_idx" ON booking.booking_records ("br_bookingTime");
CREATE INDEX submission_booking_idx ON booking.booking_submission_attempts (booking_id);

REVOKE ALL ON ALL TABLES IN SCHEMA booking FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA booking FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA booking TO oneplace_booking;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA booking TO oneplace_booking;

ALTER TABLE booking.booking_templates ENABLE ROW LEVEL SECURITY;
ALTER TABLE booking.calendar_routing_rules ENABLE ROW LEVEL SECURITY;
ALTER TABLE booking.booking_form_fields ENABLE ROW LEVEL SECURITY;
ALTER TABLE booking.booking_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE booking.booking_submission_attempts ENABLE ROW LEVEL SECURITY;
CREATE POLICY booking_backend ON booking.booking_templates TO oneplace_booking USING (true) WITH CHECK (true);
CREATE POLICY booking_backend ON booking.calendar_routing_rules TO oneplace_booking USING (true) WITH CHECK (true);
CREATE POLICY booking_backend ON booking.booking_form_fields TO oneplace_booking USING (true) WITH CHECK (true);
CREATE POLICY booking_backend ON booking.booking_records TO oneplace_booking USING (true) WITH CHECK (true);
CREATE POLICY booking_backend ON booking.booking_submission_attempts TO oneplace_booking USING (true) WITH CHECK (true);
ALTER DEFAULT PRIVILEGES IN SCHEMA booking REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA booking REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated;
COMMENT ON SCHEMA booking IS 'ONE-772 fresh booking data; historical records remain in Ragic; no public API exposure.';
